module InstructionMemory(
    input  [31:0] addr,
    output [31:0] instr
);

reg [31:0] mem [0:63];
integer i;

initial begin

    // ===========================
    // Arithmetic Instructions
    // ===========================

    mem[0]  = 32'b000000000101_00000_000_00001_0010011; // addi x1,x0,5
    mem[1]  = 32'b000000001010_00000_000_00010_0010011; // addi x2,x0,10
    mem[2]  = 32'b000000001111_00000_000_00011_0010011; // addi x3,x0,15
    mem[3]  = 32'b000000010100_00000_000_00100_0010011; // addi x4,x0,20

    // ADD
    mem[4]  = 32'b0000000_00010_00001_000_00101_0110011; // add x5,x1,x2
    mem[5]  = 32'b0000000_00100_00011_000_00110_0110011; // add x6,x3,x4

    // SUB
    mem[6]  = 32'b0100000_00001_00010_000_00111_0110011; // sub x7,x2,x1
    mem[7]  = 32'b0100000_00011_00100_000_01000_0110011; // sub x8,x4,x3

    // AND
    mem[8]  = 32'b0000000_00010_00001_111_01001_0110011; // and x9,x1,x2
    mem[9]  = 32'b0000000_00100_00011_111_01010_0110011; // and x10,x3,x4

    // OR
    mem[10] = 32'b0000000_00010_00001_110_01011_0110011; // or x11,x1,x2
    mem[11] = 32'b0000000_00100_00011_110_01100_0110011; // or x12,x3,x4

    // More ADDI
    mem[12] = 32'b000000000001_00001_000_01101_0010011; // addi x13,x1,1
    mem[13] = 32'b000000000010_00010_000_01110_0010011; // addi x14,x2,2
    mem[14] = 32'b000000000011_00011_000_01111_0010011; // addi x15,x3,3
    mem[15] = 32'b000000000100_00100_000_10000_0010011; // addi x16,x4,4

    // ===========================
    // Store Instructions
    // ===========================

    mem[16] = 32'b0000000_00101_00000_010_00000_0100011; // sw x5,0(x0)
    mem[17] = 32'b0000000_00110_00000_010_00100_0100011; // sw x6,4(x0)
    mem[18] = 32'b0000000_00111_00000_010_01000_0100011; // sw x7,8(x0)
    mem[19] = 32'b0000000_01000_00000_010_01100_0100011; // sw x8,12(x0)

    // ===========================
    // Load Instructions
    // ===========================

    mem[20] = 32'b000000000000_00000_010_10001_0000011; // lw x17,0(x0)
    mem[21] = 32'b000000000100_00000_010_10010_0000011; // lw x18,4(x0)
    mem[22] = 32'b000000001000_00000_010_10011_0000011; // lw x19,8(x0)
    mem[23] = 32'b000000001100_00000_010_10100_0000011; // lw x20,12(x0)

    // ===========================
    // Branches
    // ===========================

    mem[24] = 32'b0000000_00001_00001_000_01000_1100011; // beq x1,x1,+8
    mem[25] = 32'b0000000_00001_00010_000_01000_1100011; // beq x2,x1,+8

    // More Arithmetic
    mem[26] = 32'b0000000_10001_10010_000_10101_0110011; // add x21,x17,x18
    mem[27] = 32'b0100000_10011_10100_000_10110_0110011; // sub x22,x20,x19
    mem[28] = 32'b0000000_10101_10110_111_10111_0110011; // and x23,x21,x22
    mem[29] = 32'b0000000_10101_10110_110_11000_0110011; // or x24,x21,x22

    // ===========================
    // Fill remaining memory with NOP
    // ===========================

    for(i = 30; i < 64; i = i + 1)
        mem[i] = 32'h00000013;     // NOP (addi x0,x0,0)

end

assign instr = mem[addr[31:2]];

endmodule
